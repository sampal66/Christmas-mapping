// Star-swarm portrait generator (offline tool; Node + the preinstalled Playwright, like the other tools).
// Turns a picture into a portrait made of coloured light points for fx/portrait-swarm.js and writes it as an ES
// module. The picture itself is never committed: only the points are.
//   node tools/portrait.js <image> <out.js> <EXPORT_NAME> '<json options>'
// Options (tools/portrait-core.js): points, grid, mode ('stipple' for cartoons on black, 'led' for photos), bg
// ([r, g, b, tolerance] to key out a plain background), focus ([[cx, cy, rx, ry, weight]] ellipses, 0..1 of the image,
// that get more lights: faces), contrast, gamma, lift, edgeW, base, relax, clip ([u0, v0, u1, v1] frame limit).
// Photos: cut the people out first (transparent PNG), e.g. with a person-segmentation model in a scratch folder, and
// sharpen the faces a little; then mode 'led' with the faces as focus ellipses (see WP-08 handoff in CONTROL.md).
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

(async () => {
  const [img, out, name, json = '{}'] = process.argv.slice(2);
  if (!img || !out || !name) { console.error('usage: node tools/portrait.js <image> <out.js> <EXPORT_NAME> [json options]'); process.exit(2); }
  const opts = JSON.parse(json);
  const core = fs.readFileSync(path.join(__dirname, 'portrait-core.js'), 'utf8');
  const mime = /\.png$/i.test(img) ? 'image/png' : 'image/jpeg';
  const data = `data:${mime};base64,${fs.readFileSync(img).toString('base64')}`;
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(`<script>${core}</script>`);
  const r = await page.evaluate(async ({ data, opts }) => {
    const im = new Image(); im.src = data; await im.decode();
    return photoToPortrait(im, opts);
  }, { data, opts });
  await browser.close();
  const n = (r.d.length * 3) / 4 / 6;
  const head = `// Star-swarm portrait (${Math.round(n)} points), generated by tools/portrait.js ${JSON.stringify(opts).slice(0, 300)}\n`;
  fs.writeFileSync(out, `${head}export const ${name} = ${JSON.stringify(r)};\n`);
  console.log(`${out}: ${Math.round(n)} points, ${(fs.statSync(out).size / 1024).toFixed(1)} KB`);
})().catch((e) => { console.error(e); process.exit(1); });
