// Star-atlas figure art for the constellations (drawn faintly behind the stars, like the old celestial atlases):
// polylines in the same 0..1 box coordinates and aspect as the shapes in constellations.js.
const arc = (cx, cy, rx, ry, a0, a1, n = 14) => Array.from({ length: n + 1 }, (_, i) => {
  const a = a0 + ((a1 - a0) * i) / n;
  return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
});
const D = Math.PI / 180;

